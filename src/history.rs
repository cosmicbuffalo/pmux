/// Join parsed transcripts with live state and Codex titles, then filter and
/// sort newest-first. The same session id seen in several files (Claude keeps
/// copies when a project moves) is reported once, from its newest file.
pub(crate) fn build_history(
    metas: Vec<(PathBuf, TranscriptMeta)>,
    codex_names: &HashMap<String, String>,
    live: &LiveSessions,
    query: &HistoryQuery,
) -> Vec<HistoryEntry> {
    let mut newest: HashMap<(String, String), (PathBuf, TranscriptMeta)> = HashMap::new();
    for (path, meta) in metas {
        let key = (meta.agent.clone(), meta.session_id.clone());
        match newest.get(&key) {
            Some((_, kept)) if kept.last_activity_epoch >= meta.last_activity_epoch => {}
            _ => {
                newest.insert(key, (path, meta));
            }
        }
    }

    let mut entries: Vec<HistoryEntry> = newest
        .into_values()
        .map(|(path, meta)| {
            let (live_now, pmux_process) = live.get(&meta.agent, &meta.session_id);
            let (title, title_source) = resolve_title(&meta, codex_names);
            HistoryEntry {
                resume_command: resume_argv(&meta.agent, &meta.session_id),
                cwd_exists: meta
                    .cwd
                    .as_deref()
                    .is_some_and(|cwd| Path::new(cwd).is_dir()),
                title,
                title_source,
                live: live_now,
                pmux_process,
                last_activity_epoch: meta.last_activity_epoch.unwrap_or(0),
                transcript: path.to_string_lossy().into_owned(),
                agent: meta.agent,
                session_id: meta.session_id,
                first_prompt: meta.first_prompt,
                cwd: meta.cwd,
                git_branch: meta.git_branch,
                started_epoch: meta.started_epoch,
            }
        })
        .filter(|entry| query.include_live || !entry.live)
        .filter(|entry| query.agent.as_deref().is_none_or(|a| a == entry.agent))
        .filter(|entry| {
            query.within.as_deref().is_none_or(|root| {
                entry
                    .cwd
                    .as_deref()
                    .is_some_and(|cwd| Path::new(cwd).starts_with(root))
            })
        })
        .collect();

    entries.sort_by(|a, b| {
        b.last_activity_epoch
            .cmp(&a.last_activity_epoch)
            .then_with(|| a.session_id.cmp(&b.session_id))
    });
    if let Some(limit) = query.limit {
        entries.truncate(limit);
    }
    entries
}

fn resolve_title(
    meta: &TranscriptMeta,
    codex_names: &HashMap<String, String>,
) -> (Option<String>, Option<TitleSource>) {
    let candidates = [
        (meta.custom_title.clone(), TitleSource::Custom),
        (meta.ai_title.clone(), TitleSource::Ai),
        (
            codex_names.get(&meta.session_id).cloned(),
            TitleSource::Index,
        ),
        (meta.first_prompt.clone(), TitleSource::Prompt),
    ];
    candidates
        .into_iter()
        .find_map(|(title, source)| title.map(|title| (Some(title), Some(source))))
        .unwrap_or((None, None))
}

/// Find the entry `target` names: a full session id, `agent:id`, or an
/// unambiguous id prefix of at least four characters.
pub(crate) fn find_entry<'a>(
    entries: &'a [HistoryEntry],
    target: &str,
) -> Result<&'a HistoryEntry> {
    let (agent, id) = match target.split_once(':') {
        Some((agent, id)) => (Some(agent), id),
        None => (None, target),
    };
    let candidates: Vec<&HistoryEntry> = entries
        .iter()
        .filter(|entry| agent.is_none_or(|a| a == entry.agent))
        .collect();
    if let Some(exact) = candidates.iter().find(|entry| entry.session_id == id) {
        return Ok(exact);
    }
    if id.len() < 4 {
        bail!("session id prefix '{id}' is too short (use at least 4 characters)");
    }
    let matches: Vec<&HistoryEntry> = candidates
        .into_iter()
        .filter(|entry| entry.session_id.starts_with(id))
        .collect();
    match matches.as_slice() {
        [] => bail!("no agent session matches '{target}' (see `pmux history`)"),
        [only] => Ok(only),
        many => bail!(
            "'{target}' matches {} sessions: {}",
            many.len(),
            many.iter()
                .map(|entry| format!("{}:{}", entry.agent, entry.session_id))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}


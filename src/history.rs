//! Combined history of resumable AI agent sessions.
//!
//! Every conversation a wrapped agent ever had is resumable in principle, so
//! this module reads the agents' own session stores and merges them into one
//! catalog:
//! - Claude Code: `$CLAUDE_CONFIG_DIR/projects/<encoded-cwd>/<session-id>.jsonl`,
//!   titled by the newest `custom-title` record (set by `claude -n` or a pmux
//!   rename), else the newest `ai-title` record Claude generates itself.
//! - Codex: `$CODEX_HOME/sessions/YYYY/MM/DD/rollout-*-<session-id>.jsonl`,
//!   titled by the newest `thread_name` for the id in `session_index.jsonl`.
//!
//! Transcripts are large (hundreds of MB in total), so only a window at each
//! end of a file is read: session metadata sits at the head, and the newest
//! titles and timestamps at the tail. Results are cached in
//! `~/.local/state/pmux/history-index.json` keyed by path, mtime, and size, so
//! a refresh only reparses files that changed.
//!
//! Sessions still running somewhere are flagged `live`: inside pmux (via the
//! persisted agent identity), or anywhere else (Claude's
//! `sessions/<pid>.json` registry, Codex's held thread-writer locks). Resuming
//! a live session would put two writers on one transcript.
//!
//! Both stores are internal formats, so parsing is tolerant: an unknown or
//! malformed record is skipped, and a file that yields nothing is just absent
//! from the catalog.

use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use std::fs::{self, File};
use std::io::{BufRead, BufReader, Seek, SeekFrom};
use std::path::{Path, PathBuf};
use std::time::UNIX_EPOCH;

use crate::activity::{claude_is_prompt, codex_message_text, iso_to_epoch, prompt_text};
use crate::agents::{claude_config_dir, codex_home, cortex_home, resume_argv};
use crate::util::sanitize_terminal_text;

/// Bump when [`TranscriptMeta`] or its extraction changes, so stale cached
/// metadata is reparsed instead of trusted.
const INDEX_VERSION: u32 = 3;
/// Bytes read from the start of a transcript (always finishing the line, since
/// Codex's first record embeds the full base instructions).
const HEAD_BYTES: u64 = 512 * 1024;
/// Bytes read from the end of a transcript for the newest titles and activity.
const TAIL_BYTES: u64 = 256 * 1024;
/// Stored prompts are display text; cap them so the index stays small.
const MAX_PROMPT_CHARS: usize = 240;

/// Where an entry's title came from, in the agent's own precedence order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TitleSource {
    /// Explicitly named: `claude -n`, Claude's `/rename`, or a pmux rename.
    Custom,
    /// Generated by the agent (Claude's `ai-title`).
    Ai,
    /// Codex's `session_index.jsonl` thread name (its `/rename`, or the
    /// name Codex derives from the first prompt).
    Index,
    /// Fallback: the first real user prompt.
    Prompt,
}

/// Metadata extracted from one transcript. Cached per file, so it holds only
/// what the file itself says; live state and Codex index titles are joined
/// at query time.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct TranscriptMeta {
    pub agent: String,
    pub session_id: String,
    pub cwd: Option<String>,
    pub git_branch: Option<String>,
    pub custom_title: Option<String>,
    pub ai_title: Option<String>,
    pub first_prompt: Option<String>,
    pub started_epoch: Option<i64>,
    pub last_activity_epoch: Option<i64>,
}

/// One session in the combined catalog.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct HistoryEntry {
    pub agent: String,
    pub session_id: String,
    pub title: Option<String>,
    pub title_source: Option<TitleSource>,
    pub first_prompt: Option<String>,
    pub cwd: Option<String>,
    /// False when the session's directory is gone (e.g. a removed worktree);
    /// such sessions cannot be resumed where they ran.
    pub cwd_exists: bool,
    pub git_branch: Option<String>,
    pub started_epoch: Option<i64>,
    pub last_activity_epoch: i64,
    pub transcript: String,
    /// Running right now, in pmux or elsewhere.
    pub live: bool,
    /// The pmux process hosting this session, when it is live in pmux.
    pub pmux_process: Option<String>,
    /// The argv that resumes this session, when the agent supports it.
    pub resume_command: Option<Vec<String>>,
}

impl HistoryEntry {
    /// Whether pmux can resume this session now: it is not running anywhere,
    /// pmux knows its resume command, and its directory still exists.
    /// `pmux history --resumable` and `pmux attach <session-id>` offer only
    /// these.
    pub fn can_resume(&self) -> bool {
        !self.live && self.cwd_exists && self.resume_command.is_some()
    }
}

/// Filters for [`build_history`].
#[derive(Debug, Clone, Default)]
pub struct HistoryQuery {
    /// Include sessions that are currently running.
    pub include_live: bool,
    /// Only this agent (`claude`, `codex`, `cortex`).
    pub agent: Option<String>,
    /// Only sessions whose cwd is this directory or inside it.
    pub within: Option<PathBuf>,
    pub limit: Option<usize>,
}

/// Root directories of the agents' session stores. Missing roots are fine:
/// an agent that was never run simply contributes nothing.
#[derive(Debug, Clone)]
pub(crate) struct Sources {
    pub claude_dir: Option<PathBuf>,
    pub codex_home: Option<PathBuf>,
    pub cortex_home: Option<PathBuf>,
    /// Linux procfs root for live detection outside pmux; `None` elsewhere.
    pub proc_root: Option<PathBuf>,
}

impl Sources {
    pub fn from_env() -> Self {
        let proc_root = PathBuf::from("/proc");
        Self {
            claude_dir: claude_config_dir().ok(),
            codex_home: codex_home().ok(),
            cortex_home: cortex_home().ok(),
            proc_root: proc_root.join("self").exists().then_some(proc_root),
        }
    }
}

// ---------------------------------------------------------------------------
// Discovery and the cached index
// ---------------------------------------------------------------------------

#[derive(Debug, Default, Serialize, Deserialize)]
struct Index {
    version: u32,
    files: HashMap<String, IndexedFile>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct IndexedFile {
    mtime_ns: u64,
    size: u64,
    /// `None` records a file that holds no resumable session (no prompt yet,
    /// a non-interactive `codex exec` run), so it is not reparsed every scan.
    meta: Option<TranscriptMeta>,
}

/// List every transcript file in the agents' stores as `(agent, path)`.
fn discover(sources: &Sources) -> Vec<(&'static str, PathBuf)> {
    let mut found = Vec::new();
    if let Some(claude) = &sources.claude_dir {
        // Only direct children of each project directory: subagent
        // transcripts live in nested directories and are not resumable.
        for project in read_dir_paths(&claude.join("projects")) {
            for path in read_dir_paths(&project) {
                if path.extension().is_some_and(|ext| ext == "jsonl") && path.is_file() {
                    found.push(("claude", path));
                }
            }
        }
    }
    if let Some(codex) = &sources.codex_home {
        collect_codex_rollouts(&codex.join("sessions"), 4, &mut found);
    }
    if let Some(cortex) = &sources.cortex_home {
        for path in read_dir_paths(&cortex.join("conversations")) {
            if path
                .file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| n.ends_with(".history.jsonl"))
                && path.is_file()
            {
                found.push(("cortex", path));
            }
        }
    }
    found
}

fn collect_codex_rollouts(dir: &Path, depth: usize, found: &mut Vec<(&'static str, PathBuf)>) {
    for path in read_dir_paths(dir) {
        if path.is_dir() {
            if depth > 0 {
                collect_codex_rollouts(&path, depth - 1, found);
            }
        } else if path
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name.starts_with("rollout-") && name.ends_with(".jsonl"))
        {
            found.push(("codex", path));
        }
    }
}

fn read_dir_paths(dir: &Path) -> Vec<PathBuf> {
    fs::read_dir(dir)
        .map(|entries| entries.flatten().map(|entry| entry.path()).collect())
        .unwrap_or_default()
}

/// Parse every transcript, reusing cached metadata for unchanged files. The
/// refreshed index is written back to `cache` when anything changed; a cache
/// that cannot be read or written only costs a full reparse.
pub(crate) fn scan(sources: &Sources, cache: Option<&Path>) -> Vec<(PathBuf, TranscriptMeta)> {
    let old = cache
        .and_then(|path| fs::read_to_string(path).ok())
        .and_then(|text| serde_json::from_str::<Index>(&text).ok())
        .filter(|index| index.version == INDEX_VERSION)
        .unwrap_or_default();

    let mut next = Index {
        version: INDEX_VERSION,
        files: HashMap::new(),
    };
    let mut changed = false;
    let mut metas = Vec::new();
    for (agent, path) in discover(sources) {
        let Ok(stat) = fs::metadata(&path) else {
            continue;
        };
        let size = stat.len();
        let mtime_ns = stat
            .modified()
            .ok()
            .and_then(|time| time.duration_since(UNIX_EPOCH).ok())
            .map(|elapsed| elapsed.as_nanos() as u64)
            .unwrap_or(0);
        let key = path.to_string_lossy().into_owned();
        let entry = match old.files.get(&key) {
            Some(cached) if cached.size == size && cached.mtime_ns == mtime_ns => cached.clone(),
            _ => {
                changed = true;
                IndexedFile {
                    mtime_ns,
                    size,
                    meta: parse_transcript(agent, &path, size, mtime_ns),
                }
            }
        };
        if let Some(meta) = &entry.meta {
            let mut meta = meta.clone();
            if meta.agent == "cortex" {
                let metadata = cortex_metadata(&path, &meta.session_id);
                meta.custom_title = cortex_title(&metadata, &meta.session_id);
                meta.cwd = str_field(&metadata, "working_directory").or(meta.cwd);
            }
            metas.push((path.clone(), meta));
        }
        next.files.insert(key, entry);
    }
    changed |= next.files.len() != old.files.len();

    if changed && let Some(cache) = cache {
        let _ = write_index(cache, &next);
    }
    metas
}

// The index caches first prompts and titles, so it is written 0600.
fn write_index(path: &Path, index: &Index) -> Result<()> {
    crate::util::write_private_file_atomic(path, &serde_json::to_vec(index)?)
}

// ---------------------------------------------------------------------------
// Transcript parsing
// ---------------------------------------------------------------------------

fn parse_transcript(agent: &str, path: &Path, size: u64, mtime_ns: u64) -> Option<TranscriptMeta> {
    let lines = read_windows(path, size).ok()?;
    let mut meta = match agent {
        "claude" => parse_claude(path, &lines)?,
        "cortex" => parse_cortex(path, &lines)?,
        _ => parse_codex(path, &lines)?,
    };
    if meta.last_activity_epoch.is_none() {
        meta.last_activity_epoch = Some((mtime_ns / 1_000_000_000) as i64);
    }
    Some(meta)
}

/// Read the head and tail windows of a file as complete lines, in file order.
/// Small files are read whole; for large ones the partial line at the start of
/// the tail window is dropped.
fn read_windows(path: &Path, size: u64) -> std::io::Result<Vec<String>> {
    let mut reader = BufReader::new(File::open(path)?);
    let mut lines = Vec::new();
    let mut buf = Vec::new();
    let whole = size <= HEAD_BYTES + TAIL_BYTES;
    let mut consumed = 0u64;
    loop {
        buf.clear();
        let read = reader.read_until(b'\n', &mut buf)?;
        if read == 0 {
            return Ok(lines);
        }
        consumed += read as u64;
        lines.push(String::from_utf8_lossy(&buf).into_owned());
        if !whole && consumed >= HEAD_BYTES {
            break;
        }
    }
    let tail_start = size.saturating_sub(TAIL_BYTES).max(consumed);
    reader.seek(SeekFrom::Start(tail_start))?;
    if tail_start > consumed {
        buf.clear();
        reader.read_until(b'\n', &mut buf)?;
    }
    loop {
        buf.clear();
        if reader.read_until(b'\n', &mut buf)? == 0 {
            return Ok(lines);
        }
        lines.push(String::from_utf8_lossy(&buf).into_owned());
    }
}

fn json_lines(lines: &[String]) -> impl Iterator<Item = serde_json::Value> + '_ {
    lines
        .iter()
        .filter(|line| !line.trim().is_empty())
        .filter_map(|line| serde_json::from_str(line).ok())
}

fn str_field(v: &serde_json::Value, key: &str) -> Option<String> {
    v.get(key)
        .and_then(|s| s.as_str())
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(str::to_string)
}

/// Transcript text shown to the user (titles, prompts, branch and thread
/// names): strip terminal escapes and controls, collapse whitespace, and drop
/// what is left blank.
fn display_text(text: String) -> Option<String> {
    let clean = sanitize_terminal_text(&text)
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    (!clean.is_empty()).then_some(clean)
}

fn display_field(v: &serde_json::Value, key: &str) -> Option<String> {
    str_field(v, key).and_then(display_text)
}

fn note_times(meta: &mut TranscriptMeta, v: &serde_json::Value) {
    let Some(t) = v
        .get("timestamp")
        .and_then(|s| s.as_str())
        .and_then(iso_to_epoch)
    else {
        return;
    };
    meta.started_epoch = Some(meta.started_epoch.map_or(t, |s| s.min(t)));
    meta.last_activity_epoch = Some(meta.last_activity_epoch.map_or(t, |l| l.max(t)));
}

fn truncate_chars(text: String, max: usize) -> String {
    match text.char_indices().nth(max) {
        Some((cut, _)) => format!("{}…", text[..cut].trim_end()),
        None => text,
    }
}

fn parse_claude(path: &Path, lines: &[String]) -> Option<TranscriptMeta> {
    let mut meta = TranscriptMeta {
        agent: "claude".to_string(),
        session_id: path.file_stem()?.to_str()?.to_string(),
        ..TranscriptMeta::default()
    };
    // Older Claude versions wrote `summary` records instead of `ai-title`.
    let mut summary = None;
    for v in json_lines(lines) {
        note_times(&mut meta, &v);
        match v.get("type").and_then(|t| t.as_str()) {
            Some("custom-title") => meta.custom_title = display_field(&v, "customTitle"),
            Some("ai-title") => meta.ai_title = display_field(&v, "aiTitle"),
            Some("summary") => summary = display_field(&v, "summary"),
            _ => {}
        }
        // `claude -p` and Agent SDK runs are non-interactive one-shots.
        if str_field(&v, "entrypoint").is_some_and(|e| e.starts_with("sdk")) {
            return None;
        }
        if meta.cwd.is_none() {
            meta.cwd = str_field(&v, "cwd");
        }
        if let Some(branch) = display_field(&v, "gitBranch").filter(|b| b != "HEAD") {
            meta.git_branch = Some(branch);
        }
        if meta.first_prompt.is_none() && claude_is_prompt(&v) {
            meta.first_prompt = prompt_text(v.get("message").and_then(|m| m.get("content")))
                .and_then(display_text)
                .map(|p| truncate_chars(p, MAX_PROMPT_CHARS));
        }
    }
    meta.ai_title = meta.ai_title.or(summary);
    // A session that never received a prompt has nothing to resume.
    if meta.first_prompt.is_none() && meta.custom_title.is_none() {
        return None;
    }
    Some(meta)
}

fn cortex_metadata(path: &Path, id: &str) -> serde_json::Value {
    fs::read(path.with_file_name(format!("{id}.json")))
        .ok()
        .and_then(|s| serde_json::from_slice(&s).ok())
        .unwrap_or_default()
}

fn cortex_title(metadata: &serde_json::Value, id: &str) -> Option<String> {
    // Cortex creates this placeholder before its generated title arrives.
    // Show the real prompt instead of treating the UUID as a chosen name.
    display_field(metadata, "title").filter(|title| title != &format!("Chat for session: {id}"))
}

fn parse_cortex(path: &Path, lines: &[String]) -> Option<TranscriptMeta> {
    let id = path.file_name()?.to_str()?.strip_suffix(".history.jsonl")?;
    let metadata = cortex_metadata(path, id);
    let mut meta = TranscriptMeta {
        agent: "cortex".into(),
        session_id: id.into(),
        cwd: str_field(&metadata, "working_directory"),
        custom_title: cortex_title(&metadata, id),
        ..TranscriptMeta::default()
    };
    for v in json_lines(lines) {
        let t = v
            .get("created_on")
            .and_then(|n| n.as_i64())
            .map(|n| n / 1000)
            .or_else(|| {
                v.get("user_sent_time")
                    .and_then(|s| s.as_str())
                    .and_then(iso_to_epoch)
            });
        if let Some(t) = t {
            meta.started_epoch = Some(meta.started_epoch.map_or(t, |s| s.min(t)));
            meta.last_activity_epoch = Some(meta.last_activity_epoch.map_or(t, |s| s.max(t)));
        }
        if meta.first_prompt.is_none() && v["role"] == "user" {
            meta.first_prompt = v
                .get("content")
                .and_then(|c| c.as_array())
                .and_then(|blocks| {
                    blocks
                        .iter()
                        .find(|b| b["type"] == "text" && b["is_user_prompt"] == true)
                })
                .and_then(|b| b["text"].as_str())
                .map(str::to_string)
                .and_then(display_text)
                .map(|s| truncate_chars(s, MAX_PROMPT_CHARS));
        }
    }
    meta.first_prompt.as_ref()?;
    Some(meta)
}

fn parse_codex(path: &Path, lines: &[String]) -> Option<TranscriptMeta> {
    let mut meta = TranscriptMeta {
        agent: "codex".to_string(),
        ..TranscriptMeta::default()
    };
    for v in json_lines(lines) {
        note_times(&mut meta, &v);
        let Some(payload) = v.get("payload") else {
            continue;
        };
        match v.get("type").and_then(|t| t.as_str()) {
            Some("session_meta") if meta.session_id.is_empty() => {
                // Non-interactive `codex exec` runs and spawned sub-threads
                // are not conversations a user would resume.
                if str_field(payload, "source").as_deref() == Some("exec")
                    || str_field(payload, "thread_source").is_some_and(|s| s != "user")
                {
                    return None;
                }
                meta.session_id = str_field(payload, "id")?;
                meta.cwd = str_field(payload, "cwd");
                meta.git_branch = payload.get("git").and_then(|g| display_field(g, "branch"));
            }
            Some("response_item")
                if meta.first_prompt.is_none()
                    && payload.get("type").and_then(|t| t.as_str()) == Some("message")
                    && payload.get("role").and_then(|r| r.as_str()) == Some("user") =>
            {
                meta.first_prompt = codex_message_text(payload)
                    .and_then(display_text)
                    .map(|p| truncate_chars(p, MAX_PROMPT_CHARS));
            }
            _ => {}
        }
    }
    if meta.session_id.is_empty() {
        // Rollouts are named `rollout-<timestamp>-<uuid>.jsonl`.
        let stem = path.file_stem()?.to_str()?;
        meta.session_id = stem.get(stem.len().checked_sub(36)?..)?.to_string();
    }
    meta.first_prompt.as_ref()?;
    Some(meta)
}

/// Codex thread names by session id; the newest record per id wins.
pub(crate) fn codex_thread_names(sources: &Sources) -> HashMap<String, String> {
    let mut names = HashMap::new();
    let Some(text) = sources
        .codex_home
        .as_ref()
        .and_then(|home| fs::read_to_string(home.join("session_index.jsonl")).ok())
    else {
        return names;
    };
    for line in text.lines() {
        let Ok(v) = serde_json::from_str::<serde_json::Value>(line) else {
            continue;
        };
        if let (Some(id), Some(name)) = (str_field(&v, "id"), display_field(&v, "thread_name")) {
            names.insert(id, name);
        }
    }
    names
}


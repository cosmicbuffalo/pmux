/// Sessions running right now, keyed by `(agent, session_id)`.
#[derive(Debug, Clone, Default)]
pub(crate) struct LiveSessions {
    running: HashSet<(String, String)>,
    pmux: HashMap<(String, String), String>,
}

impl LiveSessions {
    /// Record a session hosted by the pmux process `process`.
    pub fn insert_pmux(&mut self, agent: &str, session_id: &str, process: &str) {
        let key = (agent.to_string(), session_id.to_string());
        self.running.insert(key.clone());
        self.pmux.insert(key, process.to_string());
    }

    pub fn insert(&mut self, agent: &str, session_id: &str) {
        self.running
            .insert((agent.to_string(), session_id.to_string()));
    }

    fn get(&self, agent: &str, session_id: &str) -> (bool, Option<String>) {
        let key = (agent.to_string(), session_id.to_string());
        (self.running.contains(&key), self.pmux.get(&key).cloned())
    }

    /// Add sessions running outside pmux, from each agent's own signals.
    pub fn detect_external(&mut self, sources: &Sources) {
        if let Some(claude) = &sources.claude_dir {
            self.detect_claude(&claude.join("sessions"), sources.proc_root.as_deref());
        }
        match (&sources.codex_home, &sources.proc_root) {
            (Some(codex), Some(proc_root)) => self.detect_codex(codex, proc_root),
            (Some(codex), None) => self.detect_codex_without_procfs(codex),
            _ => {}
        }
    }

    /// [`Self::detect_codex`] for systems without procfs (macOS): ask `lsof`
    /// which thread-writer locks are held open, and `ps` for `codex resume`
    /// command lines. Either tool missing just detects less; see
    /// [`codex_live_detection_available`].
    fn detect_codex_without_procfs(&mut self, codex_home: &Path) {
        let locks = codex_home.join("thread-writer-locks");
        if locks.is_dir()
            && let Ok(out) = std::process::Command::new("lsof")
                .args(["-w", "-Fn", "+d"])
                .arg(&locks)
                .stderr(std::process::Stdio::null())
                .output()
        {
            for id in codex_lock_ids_from_lsof(&String::from_utf8_lossy(&out.stdout)) {
                self.insert("codex", &id);
            }
        }
        if let Ok(out) = std::process::Command::new("ps")
            .args(["-axww", "-o", "command="])
            .stderr(std::process::Stdio::null())
            .output()
        {
            for line in String::from_utf8_lossy(&out.stdout).lines() {
                let args: Vec<&str> = line.split_whitespace().collect();
                if let Some(id) = codex_resume_target_in_args(&args) {
                    self.insert("codex", &id);
                }
            }
        }
    }

    /// Claude registers each running interactive session as
    /// `sessions/<pid>.json`. Files outlive crashed processes, so a session
    /// counts only while its pid is alive and (where recorded) still the same
    /// process, matched by start time.
    fn detect_claude(&mut self, registry: &Path, proc_root: Option<&Path>) {
        for path in read_dir_paths(registry) {
            if path.extension().is_none_or(|ext| ext != "json") {
                continue;
            }
            let Some(v) = fs::read_to_string(&path)
                .ok()
                .and_then(|text| serde_json::from_str::<serde_json::Value>(&text).ok())
            else {
                continue;
            };
            let (Some(pid), Some(session_id)) = (
                v.get("pid").and_then(|p| p.as_i64()),
                str_field(&v, "sessionId"),
            ) else {
                continue;
            };
            if pid_alive(pid, str_field(&v, "procStart").as_deref(), proc_root) {
                self.insert("claude", &session_id);
            }
        }
    }

    /// A running Codex thread holds `thread-writer-locks/<id>.lock` and its
    /// rollout file open. Older Codex releases took no lock, so a
    /// `codex resume <id>` command line also counts.
    fn detect_codex(&mut self, codex_home: &Path, proc_root: &Path) {
        for proc_dir in read_dir_paths(proc_root) {
            let is_pid = proc_dir
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.bytes().all(|b| b.is_ascii_digit()));
            if !is_pid {
                continue;
            }
            for id in codex_ids_in_proc(&proc_dir, codex_home) {
                self.insert("codex", &id);
            }
        }
    }
}

/// The Codex thread ids one process is running: a `codex resume <id>`
/// command line, or the thread-writer lock and rollout file it holds open.
fn codex_ids_in_proc(proc_dir: &Path, codex_home: &Path) -> Vec<String> {
    let locks = codex_home.join("thread-writer-locks");
    let sessions = codex_home.join("sessions");
    let mut ids: Vec<String> = codex_resume_target(proc_dir).into_iter().collect();
    for fd in read_dir_paths(&proc_dir.join("fd")) {
        let Ok(target) = fs::read_link(&fd) else {
            continue;
        };
        let id = if target.starts_with(&locks) {
            target
                .file_stem()
                .and_then(|stem| stem.to_str())
                .map(str::to_string)
        } else if target.starts_with(&sessions) {
            target
                .file_stem()
                .and_then(|stem| stem.to_str())
                .and_then(|stem| stem.get(stem.len().checked_sub(36)?..))
                .map(str::to_string)
        } else {
            None
        };
        if let Some(id) = id.filter(|id| !ids.contains(id)) {
            ids.push(id);
        }
    }
    ids
}

/// The session a live agent process is running, from that agent's own live
/// signals for `pid`: Claude's `sessions/<pid>.json` registry in the config
/// directory the process itself uses (its `CLAUDE_CONFIG_DIR`, which may not
/// be the caller's), or the one thread a Codex process holds open. Needs
/// procfs; `None` when the process names no single session.
pub(crate) fn live_session_for_pid(agent: &str, pid: i64, sources: &Sources) -> Option<String> {
    let proc_root = sources.proc_root.as_deref()?;
    let proc_dir = proc_root.join(pid.to_string());
    match agent {
        "claude" => {
            let config_dir = proc_environ_var(&proc_dir, "CLAUDE_CONFIG_DIR")
                .map(PathBuf::from)
                .or_else(|| sources.claude_dir.clone())?;
            let text =
                fs::read_to_string(config_dir.join("sessions").join(format!("{pid}.json"))).ok()?;
            let v: serde_json::Value = serde_json::from_str(&text).ok()?;
            if v.get("pid").and_then(|p| p.as_i64()) != Some(pid)
                || !pid_alive(pid, str_field(&v, "procStart").as_deref(), Some(proc_root))
            {
                return None;
            }
            str_field(&v, "sessionId")
        }
        "cortex" => {
            let id = proc_environ_var(&proc_dir, "CORTEX_SESSION_ID").or_else(|| {
                let args = fs::read(proc_dir.join("cmdline")).ok()?;
                let args: Vec<_> = args
                    .split(|b| *b == 0)
                    .filter_map(|b| std::str::from_utf8(b).ok())
                    .collect();
                args.windows(3)
                    .find(|a| a[0].rsplit('/').next() == Some("cortex") && a[1] == "resume")
                    .map(|a| a[2].to_string())
            })?;
            crate::agents::valid_session_id(&id).then_some(id)
        }
        "codex" => {
            let codex_home = proc_environ_var(&proc_dir, "CODEX_HOME")
                .map(PathBuf::from)
                .or_else(|| sources.codex_home.clone())?;
            let mut ids = codex_ids_in_proc(&proc_dir, &codex_home);
            (ids.len() == 1).then(|| ids.remove(0))
        }
        _ => None,
    }
}

/// `pid` and every process descended from it, parents before children, read
/// from procfs. Empty without procfs.
pub(crate) fn process_tree(pid: i64, sources: &Sources) -> Vec<i64> {
    let Some(proc_root) = sources.proc_root.as_deref() else {
        return Vec::new();
    };
    let mut children: HashMap<i64, Vec<i64>> = HashMap::new();
    for proc_dir in read_dir_paths(proc_root) {
        let Some(child) = proc_dir
            .file_name()
            .and_then(|name| name.to_str())
            .and_then(|name| name.parse::<i64>().ok())
        else {
            continue;
        };
        let Ok(stat) = fs::read_to_string(proc_dir.join("stat")) else {
            continue;
        };
        // Field 4 (ppid), the second field after the parenthesised comm.
        if let Some(parent) = stat
            .rsplit_once(')')
            .and_then(|(_, rest)| rest.split_whitespace().nth(1))
            .and_then(|ppid| ppid.parse::<i64>().ok())
        {
            children.entry(parent).or_default().push(child);
        }
    }
    let mut tree = vec![pid];
    let mut next = 0;
    while next < tree.len() {
        for kid in children.get(&tree[next]).cloned().unwrap_or_default() {
            if !tree.contains(&kid) {
                tree.push(kid);
            }
        }
        next += 1;
    }
    tree
}

fn proc_environ_var(proc_dir: &Path, key: &str) -> Option<String> {
    let environ = fs::read(proc_dir.join("environ")).ok()?;
    let prefix = format!("{key}=");
    environ
        .split(|b| *b == 0)
        .filter_map(|entry| std::str::from_utf8(entry).ok())
        .find_map(|entry| entry.strip_prefix(&prefix))
        .filter(|value| !value.is_empty())
        .map(str::to_string)
}

/// Whether pmux can tell that a Codex session is already running outside
/// pmux: procfs on Linux, `lsof` elsewhere.
pub(crate) fn codex_live_detection_available(sources: &Sources) -> bool {
    sources.proc_root.is_some()
        || std::process::Command::new("lsof")
            .arg("-v")
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok()
}

/// Session ids of the thread-writer locks named in `lsof -Fn` output.
fn codex_lock_ids_from_lsof(output: &str) -> Vec<String> {
    output
        .lines()
        .filter_map(|line| line.strip_prefix('n'))
        .map(Path::new)
        .filter(|path| {
            path.parent()
                .and_then(|dir| dir.file_name())
                .is_some_and(|dir| dir == "thread-writer-locks")
                && path.extension().is_some_and(|ext| ext == "lock")
        })
        .filter_map(|path| path.file_stem()?.to_str().map(str::to_string))
        .collect()
}

/// The session id in a `codex [flags] resume <id>` command line, if any.
fn codex_resume_target(proc_dir: &Path) -> Option<String> {
    let cmdline = fs::read(proc_dir.join("cmdline")).ok()?;
    let args: Vec<&str> = cmdline
        .split(|b| *b == 0)
        .filter_map(|arg| std::str::from_utf8(arg).ok())
        .collect();
    codex_resume_target_in_args(&args)
}

fn codex_resume_target_in_args(args: &[&str]) -> Option<String> {
    let codex = args.iter().position(|arg| {
        Path::new(arg)
            .file_name()
            .is_some_and(|name| name == "codex")
    })?;
    let rest = &args[codex + 1..];
    let resume = rest.iter().position(|arg| *arg == "resume")?;
    rest[resume + 1..]
        .iter()
        .find(|arg| !arg.starts_with('-'))
        .map(|id| id.to_string())
}

fn pid_alive(pid: i64, proc_start: Option<&str>, proc_root: Option<&Path>) -> bool {
    if pid <= 0 {
        return false;
    }
    let Some(proc_root) = proc_root else {
        // No procfs (macOS): signal 0 probes existence without delivering.
        // SAFETY: kill with signal 0 performs only permission/existence checks.
        let rc = unsafe { libc::kill(pid as libc::pid_t, 0) };
        return rc == 0 || std::io::Error::last_os_error().raw_os_error() == Some(libc::EPERM);
    };
    let Ok(stat) = fs::read_to_string(proc_root.join(pid.to_string()).join("stat")) else {
        return false;
    };
    let Some(expected) = proc_start else {
        return true;
    };
    // Field 22 (starttime); fields after the parenthesised comm are
    // space-separated, starting with field 3.
    stat.rsplit_once(')')
        .and_then(|(_, rest)| rest.split_whitespace().nth(19))
        .is_some_and(|start| start == expected)
}


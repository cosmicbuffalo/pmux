//! The outer-tmux integration script (`pmux tmux-init`) and applying it to a
//! running server.

use super::*;

/// The complete outer-tmux integration pmux needs, as tmux config text with the
/// binary path baked in. This is the single source of truth consumed by both
/// `pmux tmux-init` (printed for `source-file`) and [`apply_tmux_init`] (fed to
/// a running server), so the two can never disagree. It intentionally covers
/// only what pmux itself needs — the sidebar toggle, its width/stability hooks,
/// the focus hook (relay host-pane tracking plus the sidebar nudge), and
/// double/triple-click bindings that keep tmux from re-focusing the sidebar
/// after a double-click — and leaves ai-attn, window-status styling, and
/// layout keys to the user. A user's equalize binding can call
/// `pmux equalize-panes` when a sidebar is open to keep its width.
pub fn tmux_init_script(binary: &std::path::Path) -> String {
    use crate::tmux::{tmux_format_escape, tmux_quote};
    // The binary path passes through three layers, innermost first: the shell
    // run by run-shell (quote it as one word), run-shell's format expansion
    // (escape `#`), and tmux's command parser (`tmux_quote`, applied once more
    // for a hook, whose command string is parsed again when it fires). So an
    // install path containing spaces, quotes, `$` or `#` still works.
    let bin = tmux_format_escape(&crate::util::shell_quote_lossy(&binary.to_string_lossy()));
    // Single quotes are literal to tmux and keep the common case readable;
    // fall back to escaped double quotes when the value itself has a `'`.
    let word = |value: &str| {
        if value.contains('\'') {
            tmux_quote(value)
        } else {
            format!("'{value}'")
        }
    };
    let run_shell = |args: &str| format!("run-shell -b {}", word(&format!("{bin} {args}")));
    let hook =
        |name: &str, args: &str| format!("set-hook -g '{name}' {}\n", word(&run_shell(args)));
    let quiet = ">/dev/null 2>&1 || true";
    let double_click = sidebar_click_bindings();
    // Indexed hooks ([100]) and bind-key both replace their slot, so re-emitting
    // this script is idempotent and never stacks duplicate hooks.
    let mut script = String::from(
        "# pmux outer-tmux integration — generated by `pmux tmux-init`.\n\
         # Do not edit; re-run tmux-init (or update pmux) to refresh it.\n",
    );
    // pmux's own server marks itself (server.conf); this integration belongs
    // in the user's tmux, so it does nothing there but say so.
    script.push_str(
        "%if \"#{==:#{@pmux_server},1}\"\n\
         display-message -d 0 \"pmux's tmux integration belongs in your own tmux, not pmux's dedicated tmux server; it was not applied.\"\n\
         %else\n",
    );
    script.push_str(&format!(
        "bind-key C-p {}\n",
        run_shell(&format!(
            "toggle-sidebar \"#{{pane_id}}\" --socket \"#{{socket_path}}\" {quiet}"
        ))
    ));
    script.push_str(&hook(
        "pane-focus-in[100]",
        &format!(
            "on-focus \"#{{pane_id}}\" \"#{{window_id}}\" --socket \"#{{socket_path}}\" {quiet}"
        ),
    ));
    script.push_str(&hook(
        "after-resize-pane[100]",
        &format!("sidebar-width \"#{{pane_id}}\" --socket \"#{{socket_path}}\" {quiet}"),
    ));
    for name in [
        "window-resized[100]",
        "after-kill-pane[100]",
        "pane-exited[100]",
    ] {
        script.push_str(&hook(
            name,
            &format!("sidebar-stabilize \"#{{window_id}}\" --socket \"#{{socket_path}}\" {quiet}"),
        ));
    }
    script.push_str(&double_click);
    script.push_str("%endif\n");
    script
}

/// Whether the outer server has the sidebar's double/triple-click overrides
/// (see [`tmux_init_script`]) loaded. Read at double-click time so a sidebar
/// started before the integration was reloaded picks the change up at once.
pub fn sidebar_double_click_installed(context: &SidebarContext) -> bool {
    outer_tmux_output(
        &context.socket,
        &["show-options", "-gqv", SIDEBAR_DOUBLE_CLICK_OPTION],
        "read the sidebar double-click option",
    )
    .is_ok_and(|value| value.trim() == "on")
}

/// Server option set by [`tmux_init_script`] once its double/triple-click
/// overrides are installed; the sidebar reads it to act on a double-click at
/// once instead of waiting out tmux's delayed DoubleClick event.
pub const SIDEBAR_DOUBLE_CLICK_OPTION: &str = "@pmux_sidebar_double_click";

/// Double- and triple-click bindings for the outer server. tmux reports these
/// clicks only after its 300ms triple-click timer, and its defaults begin with
/// `select-pane -t =`, which re-focused the sidebar after a double-click had
/// jumped elsewhere. On a sidebar pane they now only forward the click; every
/// other pane keeps tmux's default command exactly (from
/// `tmux -f /dev/null list-keys`).
fn sidebar_click_bindings() -> String {
    let default_for = |select: &str| {
        format!(
            "select-pane -t = ; if-shell -F '#{{||:#{{pane_in_mode}},#{{mouse_any_flag}}}}' \
             {{ send-keys -M }} {{ copy-mode -H ; send-keys -X {select} ; run-shell -d 0.3 ; \
             send-keys -X copy-pipe-and-cancel }}"
        )
    };
    format!(
        "bind-key -n DoubleClick1Pane if-shell -F -t = '#{{@pmux_sidebar}}' {{ send-keys -M }} {{ {} }}\n\
         bind-key -n TripleClick1Pane if-shell -F -t = '#{{@pmux_sidebar}}' {{ send-keys -M }} {{ {} }}\n\
         set-option -g {SIDEBAR_DOUBLE_CLICK_OPTION} on\n",
        default_for("select-word"),
        default_for("select-line"),
    )
}

/// Apply [`tmux_init_script`] to a running outer tmux server by feeding it to
/// `source-file -` over stdin. Reusing the printed script guarantees an applied
/// server matches exactly what `pmux tmux-init` would emit, and lets ongoing
/// sessions pick up an updated hook set in place with no restart.
pub fn apply_tmux_init(binary: &std::path::Path, socket: &str) -> Result<()> {
    if socket.trim().is_empty() {
        bail!("outer tmux socket path must not be empty");
    }
    use std::io::Write;
    let script = tmux_init_script(binary);
    let mut child = outer_tmux_cmd(socket)?
        .args(["source-file", "-"])
        .stdin(std::process::Stdio::piped())
        .spawn()
        .context("failed to run tmux source-file for pmux integration")?;
    child
        .stdin
        .take()
        .ok_or_else(|| anyhow!("tmux source-file did not expose stdin"))?
        .write_all(script.as_bytes())
        .context("failed to send pmux integration to tmux")?;
    let status = child
        .wait()
        .context("failed to wait for tmux source-file")?;
    if !status.success() {
        bail!("tmux source-file exited with {status} while applying pmux integration");
    }
    warn_on_shared_prefix(socket);
    Ok(())
}

/// Tell the user's tmux clients when it shares a prefix with pmux: the outer
/// tmux takes the key first, so pmux's prefix never reaches pmux. Config
/// reloads run with no client, so each attached client is told directly.
fn warn_on_shared_prefix(socket: &str) {
    let read = |mut cmd: std::process::Command, option: &str| {
        cmd.args(["show-options", "-gqv", option])
            .output()
            .ok()
            .filter(|out| out.status.success())
            .map(|out| String::from_utf8_lossy(&out.stdout).trim().to_string())
            .filter(|key| !key.is_empty() && key != "None")
    };
    let pmux_prefix = if crate::tmux::pmux_server_running().unwrap_or(false) {
        read(crate::tmux::tmux_cmd(), "prefix")
    } else {
        Some("C-p".to_string())
    };
    let Some(pmux_prefix) = pmux_prefix else {
        return;
    };
    let shared = ["prefix", "prefix2"].into_iter().any(|option| {
        outer_tmux_cmd(socket)
            .ok()
            .and_then(|cmd| read(cmd, option))
            .as_deref()
            == Some(pmux_prefix.as_str())
    });
    if !shared {
        return;
    }
    // display-message expands formats; the prefix is shown literally.
    let message = crate::tmux::tmux_format_escape(&format!(
        "pmux: your tmux also uses {pmux_prefix} as its prefix, so pmux's prefix never reaches pmux. Change one of them; see `pmux doctor tmux`."
    ));
    let clients = outer_tmux_cmd(socket)
        .ok()
        .and_then(|mut cmd| {
            cmd.args(["list-clients", "-F", "#{client_name}"])
                .output()
                .ok()
        })
        .map(|out| String::from_utf8_lossy(&out.stdout).into_owned())
        .unwrap_or_default();
    for client in clients.lines().filter(|client| !client.is_empty()) {
        if let Ok(mut cmd) = outer_tmux_cmd(socket) {
            let _ = cmd
                .args(["display-message", "-d", "8000", "-c", client, &message])
                .output();
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tmux_init_script_runs_a_binary_path_with_quotes_dollars_and_hashes() {
        let Some(server) = crate::tmux::TestTmuxServer::start() else {
            return;
        };
        let (bin, log) = server.hostile_binary();
        let script = tmux_init_script(&bin);
        let sourced = server.source(&script);
        assert!(
            sourced.status.success(),
            "{}\n{script}",
            String::from_utf8_lossy(&sourced.stderr)
        );

        // Hooks: after-resize-pane and after-kill-pane fire on these commands.
        server.run(&["split-window", "-d", "-t", "=base:"]);
        server.run(&["resize-pane", "-t", "=base:.0", "-x", "50"]);
        let content = server.wait_for(&log, "sidebar-width");
        assert!(content.contains("sidebar-width\n%"), "{content}");
        server.run(&["kill-pane", "-t", "=base:.1"]);
        let content = server.wait_for(&log, "sidebar-stabilize");
        assert!(content.contains("sidebar-stabilize\n@"), "{content}");

        // Binding: run the bound command exactly as bind-key parsed it.
        let line = script
            .lines()
            .find(|line| line.starts_with("bind-key C-p "))
            .expect("bind-key C-p");
        let ran = server.source(&line["bind-key C-p ".len()..]);
        assert!(
            ran.status.success(),
            "{}",
            String::from_utf8_lossy(&ran.stderr)
        );
        let content = server.wait_for(&log, "toggle-sidebar");
        assert!(content.contains("toggle-sidebar"), "{content}");
        let content = std::fs::read_to_string(&log).unwrap_or_default();
        assert!(content.contains(&server.socket.display().to_string()));
        assert!(
            !server.hostile_marker().exists(),
            "tmux expanded #(...) in the binary path"
        );
    }

    #[test]
    fn tmux_init_script_bakes_binary_path_and_covers_the_integration() {
        let script = tmux_init_script(std::path::Path::new("/opt/pmux/bin/pmux"));
        // The resolved binary path is baked in literally (no $HOME assumption).
        assert!(script.contains("/opt/pmux/bin/pmux"));
        assert!(!script.contains("$HOME"));
        // The focus hook carries both jobs (host-pane tracking + sidebar nudge)
        // via the single on-focus subcommand, and passes both ids.
        assert!(script.contains("'pane-focus-in[100]'"));
        assert!(script.contains("on-focus"));
        assert!(script.contains("#{window_id}"));
        // Every piece of the integration pmux needs is present.
        assert!(script.contains("toggle-sidebar"));
        assert!(script.contains("'after-resize-pane[100]'"));
        assert!(script.contains("'window-resized[100]'"));
        assert!(script.contains("'after-kill-pane[100]'"));
        assert!(script.contains("'pane-exited[100]'"));
        // Layout keys belong to the user's own config.
        assert!(!script.contains("bind-key e "));
    }

    #[test]
    fn tmux_init_script_forwards_sidebar_clicks_and_keeps_tmux_defaults_elsewhere() {
        let script = tmux_init_script(std::path::Path::new("/opt/pmux/bin/pmux"));
        // On a sidebar pane, double/triple clicks only reach the renderer: no
        // select-pane to pull focus back after a double-click jumped away.
        for key in ["DoubleClick1Pane", "TripleClick1Pane"] {
            let line = script
                .lines()
                .find(|line| line.contains(key))
                .unwrap_or_else(|| panic!("{key} binding"));
            assert!(
                line.starts_with(&format!(
                    "bind-key -n {key} if-shell -F -t = '#{{@pmux_sidebar}}' {{ send-keys -M }} {{ select-pane -t = ;"
                )),
                "{line}"
            );
        }
        // Every other pane keeps tmux's default command (tmux 3.5a, from
        // `tmux -f /dev/null list-keys`).
        assert!(script.contains(
            "{ select-pane -t = ; if-shell -F '#{||:#{pane_in_mode},#{mouse_any_flag}}' \
             { send-keys -M } { copy-mode -H ; send-keys -X select-word ; run-shell -d 0.3 ; \
             send-keys -X copy-pipe-and-cancel } }"
        ));
        assert!(script.contains("send-keys -X select-line"));
        assert!(script.contains("set-option -g @pmux_sidebar_double_click on"));
    }
}

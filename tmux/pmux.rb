  # A window tab: the index, then ai-attn's indicator and the window name.
  # Use it for window-status-format, and with current: true for
  # window-status-current-format. Pass style hashes to restyle a part:
  # `index:` and `name:`, and `flash:` for the colors the tab takes while the
  # pmux sidebar flashes a process attached in that window. Optional extras:
  #
  #   gap: true          a space before the name when the window has no
  #                      indicator, so the name never touches the index
  #   zoom: {fg: ...}    show a zoomed window's name as "(name)" in this style
  #                      (unless a flash is lit)
  #   sync: {fg: ...}    a "(sync)" marker in this style while panes are
  #                      synchronized
  #
  # While ai-attn flashes a window for attention, its flash style carries from
  # the indicator through the name. While pmux flashes it, the indicator's own
  # colors are dropped so its icon takes the flash colors too.
  def window_tab(current: false, index: nil, name: nil, flash: {fg: :colour235, bg: :cyan},
    gap: false, zoom: nil, sync: nil)
    index ||= current ? {fg: :colour16, bg: :colour214, attrs: :bold} : {fg: :colour244}
    name ||= current ? {fg: :colour255, bg: :colour238} : {fg: :colour255}
    pmux_flash = option(:@pmux_flash_window) == "on"
    attention_flash = all(option(:@ai_attn_window_flash), option(:@ai_attn_flash_phase))
    any_flash = any(attention_flash, pmux_flash)
    # Expanded before its colors are stripped: a working window's segment may
    # refer to the spinner frame (#{@ai_attn_spinner_frame}) rather than hold
    # it, which tmux-ai-attn does only while every format expands the segment.
    segment = Tmux::Expression.new('#{E:@ai_attn_window_segment}')
    no_indicator = !option(:@ai_attn_window_state)
    Tmux.format do
      style(**index)
      text " #{Tmux.window_index} "
      style(**name)
      if?(pmux_flash) do
        style(**flash)
        if?(no_indicator) { text " " } if gap
        append segment.substitute('#\[[^]]*\]', "")
        style(**flash)
      end.else do
        if?(no_indicator) { text " " } if gap
        expand_option :@ai_attn_window_segment
        # The indicator ends in #[default] when it is not flashing.
        if?(!attention_flash) { style(**name) }
      end
      if zoom
        if?(Tmux.window_zoomed_flag) do
          if?(!any_flash) { style(**zoom) }
          text "(#{Tmux.window_name})"
        end.else do
          append Tmux.window_name
        end
      else
        append Tmux.window_name
      end
      text " "
      if sync
        if?(Tmux.pane_synchronized) do
          style(**sync)
          text "(sync) "
        end
      end
      reset_style
    end
  end


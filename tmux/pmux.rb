  # The sidebar toggle, its hooks, and host-pane tracking. `pmux tmux-init`
  # generates the actual commands, so they always match the installed pmux.
  def integration(pmux_bin: PMUX_BIN)
    Tmux.configure do
      comment <<~'TEXT'.chomp
        >>> pmux managed sidebar >>>
        pmux's outer-tmux integration is generated by the binary itself (via
        `pmux tmux-init`) so it can never drift out of sync with your installed pmux.
        The apply line installs the sidebar toggle, its width/stability hooks, and the
        focus hook (relay host-pane tracking + sidebar refresh nudge); it re-runs on
        every config reload, so an updated pmux upgrades the integration in place.
        The first line removes tmux-ai-attn's retired terminal-bell fallback hooks,
        leaving any user-defined alert-bell handlers intact.
      TEXT
      raw %q{run-shell -b '~/.config/pmux/clear-legacy-ai-attn-bell-hook.sh "#{socket_path}"'}
      comment <<~'TEXT'.chomp
        The outer server never inherits pmux's environment, so this line names the
        binary that generated it and falls back to `pmux` on PATH if that moved.
      TEXT
      raw %(run-shell -b 'pmux_bin="#{pmux_bin}"; [ -x "$pmux_bin" ] || pmux_bin=pmux; "$pmux_bin" tmux-init --apply --socket "\#{socket_path}" >/dev/null 2>&1 || true')
      comment "<<< pmux managed sidebar <<<"
    end
  end


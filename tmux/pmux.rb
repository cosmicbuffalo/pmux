  # What pmux starts its server with and reloads its config through.
  def server_bootstrap
    Tmux.configure do
      comment <<~'TEXT'.chomp
        The installer or first pmux command creates ~/.config/pmux/server.conf.
        pmux overwrites it when the generated-config version changes or any expected
        generated file is missing. Do not edit the installed copy; customize
        ~/.config/pmux/tmux.conf instead.

        pmux starts its dedicated tmux server with this file and reloads its config
        through it (`pmux restart`, prefix + R). The marker lets tmux.conf tell
        pmux's server apart from your own tmux, and the loading flag tells the
        managed hooks that the key bindings being made come from pmux's config
        rather than from a config loaded here by mistake.

        A server started from a pane of another tmux inherits that pane's
        TMUX_PANE. tmux replaces it in panes but not in run-shell jobs, where an
        untargeted `tmux` command would then act on an unrelated pmux pane.
      TEXT
      raw "set-environment -gu TMUX_PANE"
      global[:@pmux_server] = 1
      global[:@pmux_loading_config] = 1
      source "~/.config/pmux/tmux.conf"
      global[:@pmux_loading_config].unset
    end
  end


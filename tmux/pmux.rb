# frozen_string_literal: true

# pmux's tmux configuration, written with tmux.rb
# (https://github.com/cosmicbuffalo/tmux.rb).
#
# This file is the source of every tmux config pmux generates. `make
# templates` compiles it to the plain tmux files in templates/, which pmux
# embeds and writes to ~/.config/pmux/ for people who don't use tmux.rb.
# pmux also writes this file to ~/.config/pmux/rb/pmux.rb (overwriting it on
# upgrade, like status.conf), so tmux.rb users can build on it:
#
#   # ~/.config/pmux/tmux.conf.rb: pmux's own tmux server
#   require File.expand_path("~/.config/pmux/rb/pmux")
#   Pmux.server do
#     # your settings for pmux's server
#   end
#
#   # your own tmux config (e.g. ~/.tmux.conf.rb)
#   require File.expand_path("~/.config/pmux/rb/pmux")
#   Tmux.configure do
#     # ...your config...
#     append Pmux.integration
#     window.status.format = Pmux.window_tab
#     window.status.current_format = Pmux.window_tab(current: true)
#   end
#
# Compile either with `tmux.rb build FILE --output FILE.conf`.

require "tmux"

module Pmux
  module_function

  # The pmux binary the integration falls back from. pmux replaces the
  # placeholder with its own path when it writes the generated files.
  PMUX_BIN = "@PMUX_BIN@"

  # ---- small format helpers ------------------------------------------------
  # tmux.rb compiles `&&` / `||` only in files it loads itself, and this file
  # is loaded with require, so combined conditions and the bits of tmux
  # format language tmux.rb has no helper for are spelled out here.

  def raw(source) = Tmux.raw(source)
  def all(a, b) = raw("\#{&&:#{a},#{b}}")
  def any(a, b) = raw("\#{||:#{a},#{b}}")
  def minus(a, b) = raw("\#{e|-:#{a},#{b}}")
  def divide(a, b) = raw("\#{e|/:#{a},#{b}}")
  def times(a, b) = raw("\#{e|*:#{a},#{b}}")
  def modulo(a, b) = raw("\#{e|%:#{a},#{b}}")
  def option(name) = Tmux.user_option(name)

  # The epoch, read through strftime when a format expands it with T:, so the
  # status line never spawns date(1).
  NOW = "\#{T:@pmux_status_now}"

  # A command's first word without its directory: "/usr/bin/codex --x" -> "codex".
  def command_name(source) = raw("\#{b:\#{s| .*||:#{source}}}")

  # pmux's generated session names: `<epoch>-<8 alnum>` now, and the older
  # `<prefix>-<epoch>-<4 alnum>`.
  # Spelled out rather than with {n}, so the patterns hold no braces for
  # tmux's format parser to trip over.
  GENERATED_NAME = "^#{"[0-9]" * 10}-#{"[[:alnum:]]" * 8}$"
  LEGACY_GENERATED_NAME = "^.*-#{"[0-9]" * 10}-#{"[[:alnum:]]" * 4}$"

  # ---- pmux's server: theme ------------------------------------------------

  def theme
    Tmux.configure do
      comment <<~'TEXT'.chomp
        pmux theme configuration

        The installer or first pmux command creates ~/.config/pmux/theme.conf when it
        is missing. pmux never overwrites an existing copy. Edit it directly, then
        run `pmux restart` to apply changes. Delete it to recreate current defaults.

        Edit colors here to theme pmux statusline/hints.
      TEXT
      blank
      comment "Base status bar style."
      global[:@pmux_status_style] = "bg=#1b1f2a,fg=#c8d3f5"
      blank
      comment "Left-side styles."
      global[:@pmux_process_chip_style] = Tmux.format { style fg: "#8aadf4", bg: "#2a3142", attrs: :bold }
      global[:@pmux_age_style] = Tmux.format { style fg: "#9fb0d9", bg: "#1b1f2a" }
      blank
      comment "Prefix chip styles."
      global[:@pmux_prefix_chip_on] = Pmux.chip("^p", fg: "#1b1f2a", bg: "#f6c177", bold: true)
      global[:@pmux_prefix_chip_off] = Pmux.chip("^p", fg: "#8aadf4", bg: "#3a4258", bold: true)
      blank
      comment "Hint chips (full and compact, active/inactive)."
      hints = Tmux.format do
        ["Switch (s)", "Detach (d)", "Keys (?)"].each_with_index do |label, index|
          text " " unless index.zero?
          append Pmux.chip(label, fg: "#7dcfff", bg: "#2a3142")
        end
      end
      global[:@pmux_hints_full_on] = hints
      global[:@pmux_hints_compact_on] = hints
      global[:@pmux_hints_full_off] = ""
      global[:@pmux_hints_compact_off] = ""
    end
  end

  # A padded label in its own colors, then back to the default style.
  def chip(label, fg:, bg:, bold: false)
    Tmux.format do
      bold ? style(fg: fg, bg: bg, attrs: :bold) : style(fg: fg, bg: bg)
      text " #{label} "
      reset_style
    end
  end

  # ---- pmux's server: status line -------------------------------------------

  def status
    Tmux.configure do
      comment <<~'TEXT'.chomp
        pmux managed status formats

        This file is generated by pmux and overwritten when generated configuration
        changes. Keep theme overrides in theme.conf and status customizations in
        tmux.conf. These formats deliberately avoid #() commands: tmux runs those
        once per attached client and they can overwhelm a long-lived pmux server.
      TEXT
      blank
      comment "strftime's %s gives the current epoch without spawning date(1)."
      global[:@pmux_status_now] = Tmux.format { strftime "%s" }
      blank
      comment <<~'TEXT'.chomp
        Preserve custom session names. For generated names, show the executable from
        pmux's pane-local launch metadata, then fall back to tmux's command fields.
      TEXT
      global[:@pmux_session_label_format] = Pmux.session_label
      blank
      comment "Render compact session elapsed time with native arithmetic."
      global[:@pmux_session_age_format] = Pmux.compact_age(Pmux.minus(NOW, "\#{session_created}"))
      blank
      comment <<~'TEXT'.chomp
        Render ai-attn colors, state text, age bucketing, and three-phase working
        animation. Invalid or future timestamps render as age zero.
      TEXT
      global[:@pmux_ai_attn_format] = Pmux.ai_attn_state
      blank
      comment "ai-auto marks panes whose permission prompts are answered automatically."
      global[:@pmux_ai_auto_format] = Pmux.ai_auto_chip
      blank
      comment <<~'TEXT'.chomp
        AUTO only while ai-auto's daemon is serving the pane (fresh heartbeat);
        a leftover @ai_auto=on after the daemon stopped shows as stopped instead.
      TEXT
      global[:@pmux_ai_auto_state_format] = Pmux.ai_auto_state
      blank
      comment <<~'TEXT'.chomp
        The sidebar's label for this process: its user-chosen name, or for an
        auto-named process its agent's conversation title (italic), in the same
        rounded tag color. `pmux status-labels` publishes these options from tmux
        hooks; without a label the bracketed command chip below is shown instead.
        Reverse video draws the text in the status background on the tag color.
      TEXT
      global[:@pmux_status_pill_format] = Pmux.status_pill
      blank
      comment <<~'TEXT'.chomp
        Shown when a config from outside pmux changed this server (see the
        after-bind-key hook in tmux.conf's managed lifecycle block).
      TEXT
      global[:@pmux_foreign_config_format] =
        Pmux.chip("tmux config changed: run pmux restart --repair", fg: "#11111b", bg: "#f38ba8", bold: true)
      blank
      comment <<~'TEXT'.chomp
        pmux's popups (the attach picker, key hints, rename, queue) get a rounded,
        muted border. Set these after status.conf is sourced to change them.
      TEXT
      window.popup_border_lines = :rounded
      window.popup_border_style = "fg=#565f89"
      blank
      global.status.left = Pmux.status_left
    end
  end

  def session_label
    session = Tmux.session_name
    generated = any(session.matches(GENERATED_NAME), session.matches(LEGACY_GENERATED_NAME))
    Tmux.format do
      if?(generated) do
        if?(Pmux.option(:@pmux_launch_command)) do
          append Pmux.command_name("@pmux_launch_command")
        end.elsif?(Tmux.variable(:pane_start_command)) do
          append Pmux.command_name("pane_start_command")
        end.elsif?(Tmux.pane_current_command) do
          append Pmux.command_name("pane_current_command")
        end.else do
          append session
        end
      end.else do
        append session
      end
    end
  end

  # "42s", "17m", "5h", "3d" for an elapsed number of seconds.
  def compact_age(elapsed)
    Tmux.format do
      if?(elapsed < 60) do
        append elapsed
        text "s"
      end.elsif?(elapsed < 3600) do
        append Pmux.divide(elapsed, 60)
        text "m"
      end.elsif?(elapsed < 86_400) do
        append Pmux.divide(elapsed, 3600)
        text "h"
      end.else do
        append Pmux.divide(elapsed, 86_400)
        text "d"
      end
    end
  end

  # Coarser buckets for how long an agent has been in its state: tens of
  # seconds, then minutes, five-minute steps, hours, days.
  def bucketed_age(age)
    Tmux.format do
      if?(age < 60) do
        append Pmux.times(Pmux.divide(age, 10), 10)
        text "s"
      end.elsif?(age < 600) do
        append Pmux.divide(age, 60)
        text "m"
      end.elsif?(age < 3600) do
        append Pmux.times(Pmux.divide(age, 300), 5)
        text "m"
      end.elsif?(age < 86_400) do
        append Pmux.divide(age, 3600)
        text "h"
      end.else do
        append Pmux.divide(age, 86_400)
        text "d"
      end
    end
  end

  def ai_attn_state
    state = option(:@ai_attn_pane_state)
    updated = "\#{@ai_attn_pane_updated_at}"
    valid = all(raw("\#{e|>:#{updated},0}"), raw("\#{e|<=:#{updated},#{NOW}}"))
    age = raw("\#{?#{valid},#{minus(NOW, updated)},0}")
    phase = modulo(NOW, 3)
    Tmux.format do
      if?(state == "working") do
        style fg: "#a6e3a1"
        text "working"
        if?(phase == "0") { text "." }.elsif?(phase == "1") { text ".." }.else { text "..." }
        reset_style
      end.elsif?(state == "stopped") do
        style fg: "#f38ba8"
        text "stopped"
        reset_style
      end.else do
        # Waiting, done, or a state pmux doesn't know: the state, then how long
        # the agent has been in it.
        if?(state == "waiting") do
          style fg: "#f9e2af"
          text "attn: "
        end.elsif?(state == "done") do
          style fg: "#a6e3a1"
          text "done: "
        end.else do
          style fg: "#f9e2af"
          append state
          text ": "
        end
        append Pmux.bucketed_age(age)
        text " ago"
        reset_style
      end
    end
  end

  def ai_auto_chip
    Tmux.format do
      append Pmux.chip("AUTO", fg: "#1b1f2a", bg: "#c6a0f6", bold: true)
      if?(Pmux.option(:@ai_auto_status)) do
        text " "
        style fg: "#c6a0f6"
        append Pmux.raw("\#{=/40/…:@ai_auto_status}")
        reset_style
      end
    end
  end

  def ai_auto_state
    heartbeat = raw("\#{?@ai_auto_heartbeat,\#{@ai_auto_heartbeat},0}")
    Tmux.format do
      if?(Pmux.minus(NOW, heartbeat) < 30) do
        append Pmux.raw("\#{T:@pmux_ai_auto_format}")
      end.else do
        style fg: "#f38ba8", attrs: :bold
        text "AUTO stopped"
        reset_style
      end
    end
  end

  def status_pill
    Tmux.format do
      reset_style
      text " "
      # Rounded Powerline ends in the tag color around the reverse-video label.
      style fg: Pmux.option(:@pmux_status_pill)
      text "\u{e0b6}"
      style attrs: %i[reverse bold]
      if?(Pmux.option(:@pmux_status_label_derived)) { style :italics }
      append Pmux.option(:@pmux_status_label)
      style attrs: %i[noreverse nobold noitalics]
      text "\u{e0b4}"
      reset_style
      text " "
    end
  end

  def status_left
    label = option(:@pmux_status_label)
    pill = option(:@pmux_status_pill)
    Tmux.format do
      if?(Pmux.option(:@pmux_foreign_config)) { append Pmux.option(:@pmux_foreign_config_format) }
      if?(Pmux.all(label, pill)) do
        expand_option :@pmux_status_pill_format
      end.else do
        append Pmux.option(:@pmux_process_chip_style)
        text " ["
        append Pmux.raw("\#{T:@pmux_session_label_format}")
        text "] "
      end
      append Pmux.option(:@pmux_age_style)
      text " "
      append Pmux.raw("\#{T:@pmux_session_age_format}")
      text " ago"
      if?(Pmux.option(:@pmux_queue_status)) do
        text " "
        append Pmux.option(:@pmux_queue_status)
      end
      if?(Pmux.option(:@ai_auto) == "on") do
        text " "
        append Pmux.raw("\#{T:@pmux_ai_auto_state_format}")
      end
      if?(Pmux.option(:@ai_attn_pane_state)) do
        text " "
        append Pmux.raw("\#{T:@pmux_ai_attn_format}")
      end
      text " "
      reset_style
    end
  end

  # ---- pmux's server: lifecycle hooks (managed block) -----------------------

  STATUS_LABELS = %q{run-shell -b '"${PMUX_BIN:-pmux}" status-labels >/dev/null 2>&1 || true'}

  # The block pmux replaces in place during generated-config refreshes, so
  # plain-tmux users get hook changes without losing their edits.
  def lifecycle
    Tmux.configure do
      comment <<~'TEXT'.chomp
        >>> pmux managed lifecycle >>>
        pmux replaces this entire marked block during generated-config refreshes.
        Put custom lifecycle settings outside the markers so pmux preserves them.
        Keep the backend alive with zero sessions so the final session-closed hook runs.
      TEXT
      server.exit_empty = :off
      comment <<~'TEXT'.chomp
        Keep the restore snapshot authoritative when a process exits on its own.
        Single quotes inside keep tmux's own $VAR expansion away from ${PMUX_BIN:-pmux}.
      TEXT
      hook "session-closed", %q{run-shell -b '"${PMUX_BIN:-pmux}" snapshot >/dev/null 2>&1 || true'}, index: 100
      comment <<~'TEXT'.chomp
        Publish each process's sidebar label and tag color for the status bar
        (`pmux status-labels`). Colors depend on the whole process set and labels on
        names, so refresh when sessions come, go, or are renamed, and on every load.
        Also retry on attach and session switches: a title may have been unavailable
        at startup and agents do not necessarily change their pane title again.
        New sessions are caught by window-linked, not session-created: tmux-ai-attn
        rebuilds session-created from show-hooks output on every load, and that
        round trip drops any hook containing `$`.
      TEXT
      %w[window-linked session-renamed session-closed client-attached client-session-changed].each do |name|
        hook name, STATUS_LABELS, index: 101
      end
      comment <<~'TEXT'.chomp
        Agents put their conversation title in the pane title, behind a status glyph
        that animates while they work: one token (`✳`, `⠋`) or a bracketed group
        (`[ ! ]`). Refresh only when the text after it changes, and give the agent a
        second to write the title to its transcript. @pmux_labels_pending keeps it
        to one refresh at a time, however fast a title changes.
      TEXT
      raw <<~'TMUX'.chomp
        set-hook -g 'pane-title-changed[101]' {
          if-shell -F '#{!=:#{s/^(\[[^]]*\]|[^ ]+) //:pane_title},#{@pmux_title_seen}}' {
            set-option -pF @pmux_title_seen '#{s/^(\[[^]]*\]|[^ ]+) //:pane_title}'
            if-shell -F '#{!=:#{@pmux_labels_pending},1}' {
              set-option -g @pmux_labels_pending 1
              run-shell -b 'sleep 1; tmux set-option -gu @pmux_labels_pending; "${PMUX_BIN:-pmux}" status-labels >/dev/null 2>&1 || true'
            }
          }
        }
      TMUX
      raw STATUS_LABELS
      comment <<~'TEXT'.chomp
        Notice a tmux config meant for another server being loaded here, such as
        `tmux source-file ~/.tmux.conf` run in a pmux pane: it binds keys while
        server.conf's loading flag is unset. Flag it in the status bar and say how
        to undo it. `pmux restart --repair` clears the flag along with everything else.
      TEXT
      raw <<~'TMUX'.chomp
        set-hook -g 'after-bind-key[102]' {
          if-shell -F '#{!=:#{@pmux_loading_config},1}' {
            set -g @pmux_foreign_config 1
            display-message -d 8000 "pmux's tmux server just got key bindings from outside pmux's config. If a tmux config was loaded here by mistake, run: pmux restart --repair"
          }
        }
        set-hook -g 'after-unbind-key[102]' {
          if-shell -F '#{!=:#{@pmux_loading_config},1}' {
            set -g @pmux_foreign_config 1
          }
        }
      TMUX
      comment "<<< pmux managed lifecycle <<<"
    end
  end

  # ---- pmux's server: keys ---------------------------------------------------

  HELP = %q{run-shell -b '~/.config/pmux/help.sh --open "#{client_name}"'}

  # prefix ?, /, and h open the key hints popup.
  def help_keys
    Tmux.configure do
      comment "Key hints: pmux's own cheat sheet in place of tmux's full key list."
      %w[? / h].each { |key| bind key, HELP, note: "pmux: show key hints" }
    end
  end

  def queue_key
    Tmux.configure do
      bind "q", %q{run-shell -b 'tmux display-popup -c #{q:client_name} -w 85% -h 85% -E "${PMUX_BIN:-pmux} queue-ui \"#{pane_id}\""'},
        note: "agents: queue messages to send later"
    end
  end

  # Auto mode keys, bound only when ai-auto is installed.
  def auto_mode_keys
    Tmux.configure do
      comment <<~'TEXT'.chomp
        >>> pmux auto mode >>>
        Auto mode (ai-auto answers agent permission prompts) is bound only when
        ai-auto is installed; run `pmux restart` after installing it.
      TEXT
      if?(shell(%q{[ -x "$HOME/.local/bin/ai-auto" ] || command -v "${AI_AUTO_BIN:-ai-auto}" >/dev/null 2>&1})) do
        bind "Tab", %q{run-shell -b '"${AI_AUTO_BIN:-ai-auto}" toggle -t "#{pane_id}" -S "#{socket_path}" --message >/dev/null 2>&1 || tmux display-message "ai-auto failed (is it installed?)"'},
          note: "ai-auto: toggle auto mode for this process"
        bind "I", %q{run-shell -b 'tmux display-popup -c #{q:client_name} -w 90% -h 90% -T " ai-auto history " -E "${AI_AUTO_BIN:-ai-auto} history -t \"#{pane_id}\" -S \"#{socket_path}\" --tui --client \"#{client_name}\""'},
          note: "ai-auto: inspect auto mode history for this process"
      end
      comment "<<< pmux auto mode <<<"
    end
  end

  # Size of the popup pmux's floating prompt runs in; matches
  # PROMPT_POPUP_WIDTH/HEIGHT in src/tui/prompt.rs.
  PROMPT_WIDTH = 60
  PROMPT_HEIGHT = 9

  # The command for a key that opens pmux's floating prompt in a popup:
  # `pmux prompt` (see `pmux prompt --help`) or a pmux form built on it, so
  # every prompt looks the same. `args` follow the pmux binary inside a
  # double-quoted shell string, so quote arguments in it with \".
  #
  #   bind "B", Pmux.prompt_popup(%q{prompt --title \"New branch\" -- git switch -c})
  #
  # Every popup names the client whose key opened it (`-c`). Without a target,
  # a `tmux` run from run-shell picks a client from the server's TMUX_PANE,
  # which can name any pane or none, so the popup opened on another client.
  def prompt_popup(args)
    %(run-shell -b 'tmux display-popup -c \#{q:client_name} -w #{PROMPT_WIDTH} -h #{PROMPT_HEIGHT} -E "${PMUX_BIN:-pmux} #{args}"')
  end

  def keys
    Tmux.configure do
      global.prefix = "C-p"
      unbind "C-b"
      bind "C-p", "send-prefix", note: "pmux: send C-p to the program in this pane"
      bind "d", "detach-client", note: "process: detach"
      bind "x", Pmux.prompt_popup(%q{prompt --title \"Kill this process?\" --confirm \"This ends the process and detaches.\" --action Kill --danger -- tmux kill-pane -t \"#{pane_id}\"}),
        note: "process: kill this process and detach"
      bind "[", "copy-mode", note: "copy: copy mode (v select, y copy, q quit)"
    end
  end

  def process_keys
    Tmux.configure do
      comment "pmux process navigation"
      append Pmux.queue_key
      append Pmux.auto_mode_keys
      bind "c", Pmux.prompt_popup(%q{prompt --title \"Command for a new process\" --action Run --split -- ~/.config/pmux/new-process.sh \"#{pane_id}\"}),
        note: "process: new process running a command"
      bind "C", %q{run-shell -b "~/.config/pmux/new-process.sh '#{pane_id}'"}, note: "process: new process with a shell"
      # The picker gets this pane as its TMUX_PANE, so `pmux attach` reads the
      # current process and switches this client rather than another one.
      bind "s", %q{run-shell -b 'h=#{client_height}; [ "$h" -gt 1 ] && h=$((h-1)); tmux display-popup -c #{q:client_name} -x 0 -y 0 -w 100% -h "$h" -E "TMUX_PANE=#{pane_id} ${PMUX_BIN:-pmux} attach"'},
        note: "process: switch process, or resume a past session"
      bind "l", %q{run-shell -b '"${PMUX_BIN:-pmux}" last >/dev/null 2>&1 || true'}, note: "process: back to the last process in this pane"
      comment <<~'TEXT'.chomp
        `,` renames the process, as it renames the window in tmux. The rename form
        finds its own session, so no session name is ever spliced into shell
        text. `#{q:...}` below shell-escapes the values `k` must pass.
      TEXT
      bind ",", Pmux.prompt_popup(%q{rename-session-ui --pane \"#{pane_id}\"}),
        note: "process: rename this process"
      comment <<~'TEXT'.chomp
        `y` copies this process's name (what `pmux ls` and other pmux commands
        take) to the clipboard, e.g. to hand it to another agent session. The
        message also shows the agent title of an auto-named process.
        `pmux copy-to-clipboard` tries every route that can reach your
        clipboard: OSC 52 from pmux and from your own tmux, then a local tool
        (pbcopy, wl-copy, xclip, xsel, clip.exe) when you are not on SSH.
      TEXT
      bind "y", %q{run-shell -b '"${PMUX_BIN:-pmux}" copy-to-clipboard --client #{q:client_name} --session #{q:session_name} -- #{q:session_name} 2>/dev/null || tmux display-message -c #{q:client_name} "pmux: could not copy to the clipboard"' \; display-message "copied #{session_name}#{?@pmux_status_label_derived, (#{E:@pmux_status_label}),}"},
        note: "process: copy this process's name to the clipboard"
      bind "r", %q{source-file ~/.config/pmux/server.conf \; display-message "pmux config reloaded"}, note: "pmux: reload the pmux config"
      comment <<~'TEXT'.chomp
        n/p: cycle through processes by creation order (wrap-around).
        These use ambient pmux client state to stay easy to customize.
      TEXT
      bind "n", %q{run-shell -b '"${PMUX_BIN:-pmux}" next-process >/dev/null 2>&1 || true'}, note: "process: next process"
      bind "p", %q{run-shell -b '"${PMUX_BIN:-pmux}" prev-process >/dev/null 2>&1 || true'}, note: "process: previous process"
      bind "k", %q{run-shell -b '"${PMUX_BIN:-pmux}" kill-current-and-next #{q:session_name} #{q:client_tty} >/dev/null 2>&1 || true'},
        note: "process: kill this process, go to the next one"
      bind "a", %q{run-shell -b 'ai-attn clear --pane >/dev/null 2>&1 || true'}, note: "ai-attn: clear this pane's attention signal"
      append Pmux.help_keys
      blank
      comment "copy-mode bindings"
      bind "v", "send-keys -X begin-selection", table: "copy-mode-vi"
      bind "C-v", "send-keys -X rectangle-toggle", table: "copy-mode-vi"
      bind "C-v", "send-keys -X rectangle-toggle", table: "copy-mode"
      bind "y", "send-keys -X copy-selection-and-cancel", table: "copy-mode-vi"
    end
  end

  # Loads tmux-ai-attn (pmux's pinned copy) when ai-attn is installed.
  def ai_attn_bootstrap
    Tmux.configure do
